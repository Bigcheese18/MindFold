/**
 * 滚轮缩放的**唯一**步长来源。
 *
 * ============================================================================
 * 为什么这个文件存在（这一节的来龙去脉值得读，它是踩了坑之后才建出来的）
 * ============================================================================
 * MindFold 里滚轮有**三个**作用面：
 *   1. 主画布（`src/features/canvas/Canvas.jsx`）
 *   2. 折角弹窗右侧的 Mermaid 预览（`src/features/fold/useFoldPreview.js`）
 *   3. 打印预览页（`src/lib/printLayout.js` 生成的那份一次性 HTML）
 *
 * 这三处被**分三轮、由不同需求**分别改过，结果手感不一致，用户的原话是：
 *   「滚轮键是放大和缩小，如果要滑动的话直接用鼠标滑就行了。两个视图都是
 *     这样的，**但思维导图不是这样的**。」
 *
 * 根因不是谁写错了，而是**同一个数字被抄了三份**：每一份单独看都对，
 * 改了一份另两份不会有任何提示。所以把步长收进 `src/lib/` 这一份，
 * 三个作用面全部从这里取 —— 一致性从「约定」变成「结构」。
 *
 * 【为什么放在 src/lib/ 而不是继续留在 features/fold/previewConfig.js】
 * `printLayout.js` 是一份自包含的纯字符串模板，连 mermaid 都不碰。
 * 让它去 import `src/features/fold/` 的模块，等于「生成打印页」反向依赖
 * 「折角弹窗」，将来拆哪一边都会连着疼。放到 `src/lib/` 是唯一一个
 * **既不产生反向依赖、又只有一份数字**的位置。
 *
 * 【可以共享的只有步长，上下限不共享】
 * 三个作用面的缩放下限**必须**各用各的：
 *   主画布 0.15（要看全局）／折角预览 0.2／打印预览 0.35（要看细线）
 * 硬凑成同一个数会同时弄坏至少两个场景。所以这里只管步长。
 */

/**
 * 普通鼠标滚轮的缩放步长。
 *
 * 【为什么不是 0.1 这种「每格固定 10%」】
 * 缩放是**乘性**的，一格滚轮固定加 0.1 倍会让「已经在放大状态」时
 * 一格跳很远（1.0 → 1.1 是 10%，2.5 → 2.6 只有 4%，手感越来越钝）。
 * 这里用指数形式 `factor = exp(-deltaY * WHEEL_STEP)`：
 * deltaY 一格约 100，得到每格约 ×0.86（向下）/ ×1.16（向上），
 * 任何缩放档位下手感一致，且天然不会出现负缩放。
 */
export const WHEEL_STEP = 0.0015

/**
 * 触控板捏合的缩放步长。
 *
 * 【这个数比鼠标那档**大**，看起来反直觉，但方向是对的】
 * 浏览器把触控板捏合伪装成 `ctrlKey === true` 的 wheel 事件。两类设备的
 * deltaY 量级差了一个数量级：
 *     鼠标滚轮一格 deltaY ≈ 100（离散的「格」，事件稀疏）
 *     触控板捏合一帧 deltaY ≈ 1~10（连续手势，60 次/秒）
 * 缩放是 `exp(-deltaY × step)`，所以「精细」不能直接比 step，要比
 * **每事件的变化率**：
 *     鼠标   exp(100 × 0.0015) = 1.162  → 每格 +16.2%
 *     触控板 exp(4   × 0.01)   = 1.041  → 每帧 +4.1%
 * 触控板每帧的变化率明显更小 = 更精细、更丝滑，这正是需求要的效果；
 * 而且它事件密，累计起来才跟得上手指。
 *
 * 需求原文给的「鼠标 0.1 / 触控板 0.01」是「每事件固定倍率」模型的数字
 * （`factor = 1 + step`）。本项目用指数模型（手感在各缩放档位一致、
 * 且天然不会缩成负数），同一意图下常量必然不同 —— 但**相对关系一致**：
 * 触控板的每事件步长严格小于鼠标。
 */
export const TRACKPAD_WHEEL_STEP = 0.01
